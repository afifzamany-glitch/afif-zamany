import * as XLSX from 'xlsx';
import { db } from './database';
import { formatDisplayDate, getJakartaDate } from './time';
import { UserProfile } from '../types';

export function exportDailyReportExcel(targetDate: string, currentUser?: UserProfile) {
  const state = db.getState();
  const hotel = state.hotel;
  
  // Find all entitlements or usages for this day
  const dailyUsages = state.usages.filter((u) => u.breakfast_date === targetDate);
  const dateStr = formatDisplayDate(targetDate);

  // Rows for Excel
  const rows = dailyUsages.map((u, index) => {
    const guest = state.guests.find((g) => g.id === u.guest_id);
    const qr = state.qrCodes.find((q) => q.id === u.qr_code_id);
    return {
      'No': index + 1,
      'Breakfast Date': u.breakfast_date,
      'Time (WIB)': u.used_time_str,
      'Room Number': guest?.room_number || '-',
      'Guest Name': guest?.guest_name || '-',
      'Pax': u.pax,
      'Method': u.redemption_method === 'QR_SCAN' ? 'QR Code Scan' : 'Manual Room Search',
      'QR Token': qr?.token || '-',
      'Checked-In By': u.used_by || 'Staff',
      'Status': u.status,
    };
  });

  // Calculate summary metrics
  const totalPaxServed = dailyUsages.reduce((sum, u) => sum + u.pax, 0);
  const qrPax = dailyUsages.filter(u => u.redemption_method === 'QR_SCAN').reduce((sum, u) => sum + u.pax, 0);
  const manualPax = dailyUsages.filter(u => u.redemption_method === 'MANUAL').reduce((sum, u) => sum + u.pax, 0);

  const worksheet = XLSX.utils.json_to_sheet(rows.length > 0 ? rows : [
    { 'No': '-', 'Breakfast Date': targetDate, 'Message': 'No breakfast redemptions recorded for this date.' }
  ]);

  // Append summary at top or separate sheet
  const summaryData = [
    ['HOTEL BREAKFAST DAILY REPORT'],
    ['Hotel Name', hotel.name],
    ['Restaurant', hotel.restaurant_name],
    ['Report Date', dateStr],
    ['Generated At', new Date().toLocaleString('id-ID', { timeZone: 'Asia/Jakarta' }) + ' WIB'],
    ['Generated By', currentUser ? `${currentUser.name} (${currentUser.role})` : 'System'],
    [],
    ['METRIC SUMMARY', 'VALUE'],
    ['Total Transactions', dailyUsages.length],
    ['Total Pax Served', totalPaxServed],
    ['QR Code Redemptions (Pax)', qrPax],
    ['Manual Redemptions (Pax)', manualPax],
    [],
  ];

  const summarySheet = XLSX.utils.aoa_to_sheet(summaryData);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, summarySheet, 'Summary');
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Redemption Details');

  // Trigger browser download
  const filename = `Tjokro_Breakfast_Daily_${targetDate}.xlsx`;
  XLSX.writeFile(workbook, filename);

  db.addAuditLog(
    'REPORT_EXPORTED',
    'report_exports',
    `rep-daily-${targetDate}`,
    { type: 'DAILY_EXCEL', date: targetDate, rowsCount: dailyUsages.length },
    currentUser
  );
}

export function exportMonthlyReportExcel(yearMonth: string, currentUser?: UserProfile) {
  const state = db.getState();
  const hotel = state.hotel;
  
  // Format: YYYY-MM
  const monthlyUsages = state.usages.filter((u) => u.breakfast_date.startsWith(yearMonth));

  // Daily breakdown map
  const dailySummaryMap: Record<string, { date: string; transactions: number; pax: number; qrPax: number; manualPax: number }> = {};

  monthlyUsages.forEach((u) => {
    if (!dailySummaryMap[u.breakfast_date]) {
      dailySummaryMap[u.breakfast_date] = {
        date: u.breakfast_date,
        transactions: 0,
        pax: 0,
        qrPax: 0,
        manualPax: 0,
      };
    }
    dailySummaryMap[u.breakfast_date].transactions += 1;
    dailySummaryMap[u.breakfast_date].pax += u.pax;
    if (u.redemption_method === 'QR_SCAN') {
      dailySummaryMap[u.breakfast_date].qrPax += u.pax;
    } else {
      dailySummaryMap[u.breakfast_date].manualPax += u.pax;
    }
  });

  const summaryRows = Object.values(dailySummaryMap).sort((a, b) => a.date.localeCompare(b.date)).map((item, idx) => ({
    'No': idx + 1,
    'Date': item.date,
    'Formatted Date': formatDisplayDate(item.date),
    'Total Check-ins': item.transactions,
    'Total Pax Served': item.pax,
    'QR Scan Pax': item.qrPax,
    'Manual Search Pax': item.manualPax,
  }));

  const detailRows = monthlyUsages.map((u, index) => {
    const guest = state.guests.find((g) => g.id === u.guest_id);
    return {
      'No': index + 1,
      'Date': u.breakfast_date,
      'Time (WIB)': u.used_time_str,
      'Room': guest?.room_number || '-',
      'Guest Name': guest?.guest_name || '-',
      'Pax': u.pax,
      'Redemption Method': u.redemption_method,
      'Handled By': u.used_by || 'Staff',
    };
  });

  const workbook = XLSX.utils.book_new();

  // Header info
  const headerData = [
    ['HOTEL BREAKFAST MONTHLY REPORT'],
    ['Hotel Name', hotel.name],
    ['Restaurant', hotel.restaurant_name],
    ['Month Period', yearMonth],
    ['Total Pax Month-to-Date', monthlyUsages.reduce((sum, u) => sum + u.pax, 0)],
    ['Total Transactions', monthlyUsages.length],
    ['Generated At', new Date().toLocaleString('id-ID', { timeZone: 'Asia/Jakarta' }) + ' WIB'],
    [],
  ];
  const overviewSheet = XLSX.utils.aoa_to_sheet(headerData);
  XLSX.utils.book_append_sheet(workbook, overviewSheet, 'Monthly Overview');

  const summarySheet = XLSX.utils.json_to_sheet(summaryRows.length > 0 ? summaryRows : [{ Message: 'No data for this month' }]);
  XLSX.utils.book_append_sheet(workbook, summarySheet, 'Daily Breakdown');

  const detailSheet = XLSX.utils.json_to_sheet(detailRows.length > 0 ? detailRows : [{ Message: 'No data for this month' }]);
  XLSX.utils.book_append_sheet(workbook, detailSheet, 'All Transactions');

  const filename = `Tjokro_Breakfast_Monthly_${yearMonth}.xlsx`;
  XLSX.writeFile(workbook, filename);

  db.addAuditLog(
    'REPORT_EXPORTED',
    'report_exports',
    `rep-monthly-${yearMonth}`,
    { type: 'MONTHLY_EXCEL', period: yearMonth, totalPax: monthlyUsages.reduce((sum, u) => sum + u.pax, 0) },
    currentUser
  );
}
